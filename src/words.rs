pub(crate) const WORD_COUNTS: &[usize] = &[10, 25, 50, 100];
pub(crate) const TIME_LIMITS: &[u64] = &[15, 30, 60, 120];

const INITIAL_BATCH_WORDS: usize = 35;
const APPEND_BATCH_WORDS: usize = 20;
const APPEND_THRESHOLD_WORDS: usize = 10;

impl App {
    pub(crate) fn generate_text(&mut self) {
        let mut rng = rand::thread_rng();
        let count = match self.mode {
            TestMode::Words => self.word_count,
            TestMode::Time => INITIAL_BATCH_WORDS,
        };
        let words: Vec<&str> = WORD_BANK
            .choose_multiple(&mut rng, count)
            .copied()
            .collect();
        self.text = words.join(" ");
    }

    pub(crate) fn restart(&mut self) {
        let mode = self.mode;
        let wc = self.word_count;
        let time_limit = self.time_limit_secs;
        *self = Self::new();
        self.mode = mode;
        self.word_count = wc;
        self.time_limit_secs = time_limit;
        self.generate_text();
    }

    pub(crate) fn append_words(&mut self) {
        let mut rng = rand::thread_rng();
        let words: Vec<&str> = WORD_BANK
            .choose_multiple(&mut rng, APPEND_BATCH_WORDS)
            .copied()
            .collect();
        if !self.text.is_empty() {
            self.text.push(' ');
        }
        self.text.push_str(&words.join(" "));
    }

    pub(crate) fn extend_if_needed(&mut self) {
        if self.mode != TestMode::Time {
            return;
        }
        let remaining_words = self.text[self.typed.len()..].split_whitespace().count();
        if remaining_words <= APPEND_THRESHOLD_WORDS {
            self.append_words();
        }
    }

    pub(crate) fn set_word_count(&mut self, count: usize) {
        if self.start_time.is_some() {
            return;
        }
        self.word_count = count;
        self.typed.clear();
        self.delay_queue.clear();
        self.cursor = 0;
        self.generate_text();
    }

    pub(crate) fn set_time_limit(&mut self, secs: u64) {
        if self.start_time.is_some() {
            return;
        }
        self.time_limit_secs = secs;
    }
}
